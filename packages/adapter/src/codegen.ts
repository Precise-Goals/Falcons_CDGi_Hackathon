/**
 * TypeScript Source Code Generator for Autonomous Safe-Handling Adapters
 */

export interface CodegenOptions {
  changeId: string;
  service: string;
  endpoint: string;
  functionName?: string;
  transformationBody: string;
  testInput: unknown;
  expectedOutput: unknown;
  rollbackHandle?: string;
}

export interface GeneratedAdapterModule {
  sourceCode: string;
  testCode: string;
  fileName: string;
  testFileName: string;
}

/**
 * Generates standalone, zero-dependency TypeScript code and Vitest test suite for an adapter.
 */
export function generateAdapterSourceCode(options: CodegenOptions): GeneratedAdapterModule {
  const fnName = options.functionName ?? 'adaptResponse';
  const timestamp = new Date().toISOString();
  const sanitizedService = options.service.replace(/[^a-zA-Z0-9]/g, '_');
  const fileName = `adapt_${sanitizedService}_${options.changeId}.ts`;
  const testFileName = `adapt_${sanitizedService}_${options.changeId}.test.ts`;

  const sourceCode = `/**
 * Autonomous Compatibility Adapter for ${options.service} [${options.endpoint}]
 * Generated by Intra Safe-Handling Engine at ${timestamp}
 * Drift ID: ${options.changeId}
 * Rollback Handle: ${options.rollbackHandle ?? 'none'}
 *
 * ZERO EXTERNAL DEPENDENCIES. PURE DETERMINISTIC RUNTIME.
 */

export function ${fnName}<T = unknown, R = unknown>(payload: T): R {
  if (Array.isArray(payload)) {
    return (payload as unknown[]).map(item => transformSingle(item)) as unknown as R;
  }
  return transformSingle(payload) as unknown as R;
}

function transformSingle(data: unknown): unknown {
  if (data === null || data === undefined || typeof data !== 'object') {
    return data;
  }
  const item = { ...(data as Record<string, unknown>) };
  ${options.transformationBody}
  return item;
}
`.trim();

  const testCode = `import { describe, it, expect } from 'vitest';
import { ${fnName} } from './${fileName.replace(/\.ts$/, '.js')}';

describe('Autonomous Adapter [${options.changeId}]', () => {
  it('correctly adapts drifted payload into client schema', () => {
    const input = ${JSON.stringify(options.testInput, null, 2)};
    const expected = ${JSON.stringify(options.expectedOutput, null, 2)};

    const result = ${fnName}(input);
    expect(result).toEqual(expected);
  });
});
`.trim();

  return {
    sourceCode,
    testCode,
    fileName,
    testFileName,
  };
}
